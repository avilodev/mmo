"""Copy the item fields the client shows into Game/data/items.json.

Run from mmo_client/ (or `make items`):

    python3 Game/tools/sync_items.py

The server's items.json is the only master. The client file is generated from
it and must not be edited by hand: it keeps just the fields a player can see
in a tooltip, an equip prompt or the shop, and drops the rest (the top-level
loot_tables, and any field not listed in CLIENT_FIELDS). Run it again whenever
the server file changes.

The client reads this file with a small hand-rolled parser (inventory item
database, Game/src/player/item_db.c), so a description may not hold a quote, a
backslash or a control character, and the file's comment may not contain a
quoted "items". Both are checked here.
"""

import json
import os
import sys

TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
SERVER_PATH = os.path.normpath(os.path.join(
    TOOLS_DIR, "..", "..", "..", "mmo_server", "world_server", "data", "items.json"))
CLIENT_PATH = os.path.normpath(os.path.join(TOOLS_DIR, "..", "data", "items.json"))

# One entry per StatId, in enum order (protocol.h, race_registry.c k_stat_keys).
STAT_KEYS = ("strength", "dexterity", "vitality", "intelligence", "focus", "endurance",
             "ferocity", "stamina_capacity", "precision", "ferality", "armor")

# Races one item can be limited to (ItemDefinition.race_req on the server).
MAX_RACE_REQ = 4

# Every field the client may know. Adding one here is the only step needed to
# let it through; the client parser still has to read it.
CLIENT_FIELDS = (
    "id", "name", "description", "type", "slot", "rarity", "max_stack",
    "damage", "defense", "level_req", "value",
    "bind_on_pickup", "bind_on_equip", "race_req",
    "use_effect", "use_value", "use_cooldown",
) + tuple("bonus_" + key for key in STAT_KEYS)

COMMENT = ("Generated by Game/tools/sync_items.py from "
           "mmo_server/world_server/data/items.json. Do not edit by hand; edit the "
           "server file and run the script again. Holds only the fields the client "
           "shows a player.")


class ItemSyncError(Exception):
    pass


def check_item(item: object, index: int, seen_ids: set) -> None:
    where = "item %d" % index
    if not isinstance(item, dict):
        raise ItemSyncError("%s is not an object" % where)
    item_id = item.get("id")
    if not isinstance(item_id, int) or isinstance(item_id, bool):
        raise ItemSyncError("%s has no integer id" % where)
    where = "item %d" % item_id
    name = item.get("name")
    if not isinstance(name, str) or not name:
        raise ItemSyncError("%s has no name" % where)
    if item_id in seen_ids:
        raise ItemSyncError("%s is defined more than once" % where)
    seen_ids.add(item_id)
    race_req = item.get("race_req", [])
    if (not isinstance(race_req, list) or len(race_req) > MAX_RACE_REQ
            or not all(isinstance(r, int) and not isinstance(r, bool) and 0 < r < 256
                       for r in race_req)):
        raise ItemSyncError("%s: race_req must be a list of up to %d race ids (1-255)"
                            % (where, MAX_RACE_REQ))
    description = item.get("description", "")
    if not isinstance(description, str):
        raise ItemSyncError("%s: description is not text" % where)
    if any(c in '"\\' or ord(c) < 32 or ord(c) > 126 for c in description + name):
        raise ItemSyncError(
            "%s: name and description must be plain ASCII with no quote or backslash" % where)


def slice_items(server_doc: object) -> tuple:
    """Return (client_doc, dropped_fields) for a parsed server items.json."""
    items = server_doc.get("items") if isinstance(server_doc, dict) else None
    if not isinstance(items, list):
        raise ItemSyncError("server file has no items list")

    seen_ids = set()
    client_items = []
    dropped = set()
    for index, item in enumerate(items):
        check_item(item, index, seen_ids)
        client_items.append({key: item[key] for key in CLIENT_FIELDS if key in item})
        dropped.update(key for key in item if key not in CLIENT_FIELDS)

    return {"_comment": COMMENT, "items": client_items}, sorted(dropped)


def sync(server_path: str = SERVER_PATH, client_path: str = CLIENT_PATH) -> tuple:
    with open(server_path, encoding="utf-8") as f:
        server_doc = json.load(f)

    client_doc, dropped = slice_items(server_doc)

    with open(client_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(client_doc, f, indent=2)
        f.write("\n")

    return len(client_doc["items"]), dropped


def main() -> int:
    try:
        count, dropped = sync()
    except (OSError, ValueError, ItemSyncError) as err:
        print("sync_items: %s" % err, file=sys.stderr)
        return 1

    print("sync_items: wrote %d items to %s" % (count, CLIENT_PATH))
    if dropped:
        print("sync_items: server-only item fields not copied: %s" % ", ".join(dropped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
